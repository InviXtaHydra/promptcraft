import type { z } from "zod";
import type { personaSchema } from "@/content/scenario-schema";

export type Persona = z.infer<typeof personaSchema>;

/** What a dialogue provider may know: only this NPC, this player's state, and this NPC's memories. */
export type DialogueContext = {
  npc: { key: string; name: string; persona: Persona };
  message: string;
  /** How many messages the player sent this NPC before this one */
  previousPlayerMessages: number;
  trust: number;
  suspicion: number;
  alert: number;
  locationKey: string;
  questStatus: ReadonlyMap<string, "ACTIVE" | "COMPLETED" | "FAILED">;
  objectivesDone: ReadonlySet<string>;
  evidence: ReadonlySet<string>;
  inventory: ReadonlySet<string>;
  /** This NPC's memories of the player, most important first */
  memories: readonly string[];
  /** Price per item key this NPC sells, already resolved for the player's trust */
  offers: ReadonlyMap<string, { name: string; price: number; discounted: boolean }>;
};

export type DialogueReply = {
  text: string;
  /** Short label of what the provider understood, shown in traces (e.g. "ask_about_badge") */
  intent: string;
  /** One-line decision summary for the trace. Never hidden reasoning. */
  summary: string;
  /** Proposed effects; the engine validates every one (policy.ts, apply.ts) */
  proposals: unknown[];
};

export interface DialogueProvider {
  readonly id: string;
  readonly model: string;
  /** True when replies are scripted, not generated by a language model */
  readonly isSimulated: boolean;
  reply(context: DialogueContext): Promise<DialogueReply>;
  /** The NPC's reaction when the player hands over an item for a quest */
  reactToItem(context: DialogueContext, itemKey: string): Promise<DialogueReply>;
  /** Things the player could say next, for the chat's suggestion chips */
  suggestions(context: Omit<DialogueContext, "message">): string[];
}
