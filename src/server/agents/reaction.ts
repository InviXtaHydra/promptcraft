import { loadSessionContext } from "../engine/context";
import type { OutcomeSummary } from "../engine";
import { buildNpcContext } from "./npc-context";
import { retrieveMemories } from "./memory";
import type { TurnDeps } from "./npc-turn";
import { TraceRecorder, type TurnEvent } from "./trace";
import { playerMessageFor, ProviderError } from "../ai/errors";

/**
 * When a model voices the NPCs, the reaction to a handed-over item is generated after the give
 * command committed, as its own short run (load_state → retrieve_memories → respond). If the model
 * fails, the run fails and no line is invented; the game state is already correct either way.
 */
export async function generateItemReaction(
  deps: TurnDeps,
  input: { userId: string; sessionId: string; npcKey: string; itemKey: string; outcomes: OutcomeSummary[] },
  onEvent: (e: TurnEvent) => void = () => undefined,
) {
  const { prisma, brain, embedder, config } = deps;
  const ctx = await loadSessionContext(prisma, input.sessionId, input.userId);
  const npc = ctx.content.npcs.get(input.npcKey)!;
  const conversation = await prisma.conversation.findUniqueOrThrow({ where: { gameSessionId_npcId: { gameSessionId: input.sessionId, npcId: npc.id } } });
  const run = await prisma.agentRun.create({
    data: { gameSessionId: input.sessionId, userId: input.userId, npcId: npc.id, provider: brain.provider, model: brain.model, isSimulated: brain.isSimulated },
  });
  const trace = new TraceRecorder(prisma, run.id, onEvent);
  const started = Date.now();
  const signal = AbortSignal.timeout(config.AI_TURN_TIMEOUT_MS);
  const itemName = ctx.content.items.get(input.itemKey)?.name ?? "item";
  const said = `(The player hands you the ${itemName}.)`;
  try {
    const memories = await trace.step("retrieve_memories", async () => {
      const m = await retrieveMemories(prisma, embedder, { userId: input.userId, npcKey: npc.key, gameSessionId: input.sessionId }, said, signal);
      return { value: m, summary: `${m.length} memories recalled.` };
    });
    const npcContext = await trace.step("build_npc_context", async () => ({ value: await buildNpcContext(prisma, ctx, npc.key, said, memories), summary: "Context for the reaction." }));
    const r = await trace.step("respond", async () => {
      const result = await brain.respond(npcContext, { applied: input.outcomes.filter((o) => o.status === "applied").map((o) => o.text), rejected: [], lookedUp: [] }, signal, (text) => onEvent({ type: "delta", text }));
      return { value: result, summary: `Reaction generated by ${brain.model}.`, data: { usage: result.usage, latencyMs: result.latencyMs } };
    });
    await prisma.message.create({ data: { conversationId: conversation.id, role: "NPC", content: r.value, provider: brain.provider, isSimulated: brain.isSimulated, agentRunId: run.id } });
    await prisma.agentRun.update({
      where: { id: run.id },
      data: { status: "SUCCEEDED", finishedAt: new Date(), latencyMs: Date.now() - started, inputTokens: r.usage?.inputTokens ?? 0, outputTokens: r.usage?.outputTokens ?? 0, modelCalls: 1, retries: r.retries ?? 0, transitions: trace.transitions, estimatedCostUsd: 0 },
    });
    return { ok: true as const };
  } catch (error) {
    const code = error instanceof ProviderError ? error.code : "provider_error";
    await prisma.agentRun.update({ where: { id: run.id }, data: { status: "FAILED", finishedAt: new Date(), latencyMs: Date.now() - started, error: String((error as Error)?.message ?? error).slice(0, 500), transitions: trace.transitions } });
    return { ok: false as const, message: playerMessageFor(code) };
  }
}
